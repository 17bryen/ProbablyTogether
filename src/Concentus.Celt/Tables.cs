	internal static short[] GenerateFftTwiddles(int nfft)
	{
		short[] array = new short[nfft * 2];
		for (int i = 0; i < nfft; i++)
		{
			int num = (-i << 17) / nfft;
			array[2 * i] = (short)Inlines.celt_cos_norm(num);
			array[2 * i + 1] = (short)Inlines.celt_cos_norm(num - 32768);
		}
		return array;
	}

	internal static short[] GenerateMdctTwiddles(int n, int maxshift)
	{
		int num = n >> 1;
		short[] array = new short[n - (num >> maxshift)];
		int num2 = 0;
		for (int i = 0; i <= maxshift; i++)
		{
			for (int j = 0; j < num; j++)
			{
				array[num2++] = (short)Math.Max(-32767.0, Math.Min(32767.0, Math.Floor(0.5 + 32768.0 * Math.Cos(Math.PI * 2.0 * ((double)j + 0.125) / (double)n))));
			}
			num >>= 1;
			n >>= 1;
		}
		return array;
	}
